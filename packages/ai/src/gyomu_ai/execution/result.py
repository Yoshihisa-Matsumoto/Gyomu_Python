from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal
from types import TracebackType
from typing import Any, Literal, Protocol, Self

from gyomu_schema.conversation.conversation import ConversationSchema
from gyomu_schema.conversation.message import AiTextPart, MessageSchema
from pydantic import BaseModel


@dataclass(frozen=True)
class AiToolUsage:
    """Represents token usage statistics for tool execution."""

    input_tokens: int
    """The number of input tokens consumed."""

    output_tokens: int
    """The number of output tokens generated."""

    total_tokens: int
    """The total number of tokens consumed and generated."""


@dataclass(frozen=True)
class AiToolCallResultPart:
    """Represents the result of a tool call execution part."""

    tool_name: str
    """The name of the tool called."""

    tool_call_id: str
    """The unique identifier for the tool call."""

    input: Any
    """The input parameters provided to the tool."""

    output: Any | None
    """The output result returned by the tool, if any."""

    elapsed_second: float | None
    """The time elapsed in seconds for the tool call, if any."""


@dataclass(frozen=True)
class AiToolCallGroup:
    """Represents a group of tool calls with their combined usage statistics."""

    calls: list[AiToolCallResultPart]
    """The list of tool call result parts."""

    usage: AiToolUsage
    """The tool usage statistics for the group."""


@dataclass(frozen=True)
class AiTextDeltaResultPart:
    """Represents a text delta result part in streaming responses."""

    text: str
    """The text delta content."""


type AiMessagePart = AiTextPart | AiToolCallResultPart
"""Represents a part of an AI message, which can be text or a tool call result."""

type AiStreamEvent = AiTextDeltaResultPart | AiToolCallResultPart
"""Represents an event emitted during a stream, which can be a text delta or a tool
call result.
"""


@dataclass(frozen=True)
class AiAssistantTextMessage:
    """Represents a text message generated by the AI assistant."""

    parts: tuple[AiMessagePart, ...]
    """The sequence of message parts comprising the assistant response."""

    text: str
    """The concatenated text content of the message."""

    @classmethod
    def from_message(
        cls,
        message: MessageSchema,
    ) -> Self:
        """Creates an assistant text message from a conversation message schema."""

        text = "\r\n".join(
            part.text for part in message.parts if isinstance(part, AiTextPart)
        )
        return cls(parts=message.parts, text=text)


AiFinishReason = Literal[
    "completed",
    "max-tokens",
    "tool-call",
    "content-filtered",
    "error",
    "cancelled",
    "unknown",
]
"""Represents the reason why generation finished."""


@dataclass(frozen=True)
class AiUsage:
    """Represents token usage statistics and cost information for an AI generation."""

    input_tokens: int
    """The number of input tokens consumed."""

    output_tokens: int
    """The number of output tokens generated."""

    total_tokens: int
    """The total number of tokens consumed and generated."""

    cost: Decimal | None
    """The monetary cost associated with the generation, if available."""


@dataclass(frozen=True)
class AiGenerationMetadata:
    """Represents metadata associated with an AI generation execution."""

    started_at: datetime
    """The timestamp when the generation started."""

    completed_at: datetime
    """The timestamp when the generation completed."""

    elapsed_second: float
    """The duration of the generation in seconds."""

    usage: AiUsage
    """The token usage and cost statistics for the generation."""

    finish_reason: AiFinishReason | None
    """The reason why the generation finished, if available."""

    tool_calls: AiToolCallGroup | None
    """The tool calls executed during the generation, if any."""


@dataclass(frozen=True)
class AiGenerateTextResult:
    """Represents the result of a text generation operation, including message,
    metadata, and conversation.
    """

    message: AiAssistantTextMessage
    """The generated assistant text message."""

    metadata: AiGenerationMetadata
    """The generation metadata."""

    conversation: ConversationSchema
    """The updated conversation schema."""


@dataclass(frozen=True)
class AiGenerateObjectResult[T: BaseModel]:
    """Represents the result of structured object generation."""

    output: T
    """The generated structured output object."""

    metadata: AiGenerationMetadata
    """The generation metadata."""


class AiTextStream(Protocol):
    """Protocol representing a stream of text generation results."""

    async def __aenter__(self) -> Self: ...

    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc_value: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...

    def __aiter__(self) -> Self: ...

    async def __anext__(self) -> str: ...

    @property
    def result(self) -> AiGenerateTextResult | None: ...

    """Gets the final generation result once the stream completes.

    Gets the final generation result once the stream completes.
    """

    """Gets the final generation result once the stream completes."""


@dataclass(frozen=True)
class AiEmbeddingResult:
    """Represents the result of embedding vector generation."""

    vector: Sequence[Sequence[float]]
    """The generated embedding vectors."""

    metadata: AiGenerationMetadata
    """The generation metadata."""
